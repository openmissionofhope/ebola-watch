import type { EvalDataset, Evaluation } from "../api";
import { DataTable } from "../components/DataTable";
import { PageHead } from "../components/Layout";
import { Async } from "../components/Status";
import { CoverageChart, PitChart } from "../charts/EvalCharts";
import { fmtDateTime, fmtNum, fmtPct } from "../format";
import { useApi, useDocumentTitle } from "../hooks";
import { t, tx } from "../i18n";

export function EvaluationPage() {
  useDocumentTitle(t("Forecasts & evaluation"));
  const ev = useApi<Evaluation>("/evaluation");
  return (
    <>
      <PageHead title={t("Forecast evaluation")} />
      <p className="secondary">
        {t(
          "Retrospective evaluation (“backtesting”): the model is refitted using only data available at each past date, and its forecasts are compared with what was later reported. Results are shown as computed, including poor ones. Well-calibrated 90% intervals contain the observed value about 90% of the time.",
        )}
      </p>
      <Async state={ev}>
        {(d) => (
          <>
            <p className="small muted">{t("Model {version}.", { version: d.model_version })} {tx(d.note)}</p>
            <h2 className="section">{t("Real outbreak data")}</h2>
            {d.datasets.filter((x) => !x.is_synthetic).map((x) => <DatasetCard key={x.dataset} d={x} />)}
            {!d.datasets.some((x) => !x.is_synthetic) && <p className="muted">{t("No official series is long enough for backtesting yet.")}</p>}
            <h2 className="section">{t("Synthetic outbreaks (calibration checks with known truth)")}</h2>
            <p className="small">{t("These datasets are generated by the model's own simulator and are labelled SYNTHETIC. They test the machinery, not real-world accuracy.")}</p>
            {d.datasets.filter((x) => x.is_synthetic).map((x) => <DatasetCard key={x.dataset} d={x} />)}
            <section className="card section">
              <h2>{t("Early-warning detection performance")}</h2>
              <p><strong>{tx(d.detection_performance.status)}</strong>: {tx(d.detection_performance.reason)}.</p>
            </section>
          </>
        )}
      </Async>
    </>
  );
}

function DatasetCard({ d }: { d: EvalDataset }) {
  const bh = d.summary?.by_horizon ?? {};
  const hs = Object.keys(bh).sort((a, b) => +a - +b);
  return (
    <section className="card section" aria-label={t("Evaluation: {dataset}", { dataset: d.dataset })}>
      <div className="card-head">
        <h3 style={{ margin: 0 }} translate="no">{d.dataset}</h3>
        <span className={`badge ${d.is_synthetic ? "synthetic" : "official"}`}>{tx(d.label)}</span>
      </div>
      <p className="small muted">
        {t("Evaluated {when} · {n} forecasts evaluated", { when: fmtDateTime(d.run_at), n: d.summary?.n ?? 0 })}
      </p>
      {d.notes.map((n) => <p key={n} className="small">{t("Note: {text}", { text: tx(n) })}</p>)}
      {hs.length === 0 ? (
        <p className="muted">{t("Not enough data to evaluate.")}</p>
      ) : (
        <>
          <div className="grid cols-3">
            <div><h4>{t("Coverage of 50% intervals")}</h4><CoverageChart byHorizon={bh} which={50} /></div>
            <div><h4>{t("Coverage of 90% intervals")}</h4><CoverageChart byHorizon={bh} which={90} /></div>
            <div>
              <h4>{t("PIT histogram (all horizons)")}</h4>
              <PitChart bins={hs.reduce((acc, h) => acc.map((v, i) => v + (bh[h].pit_histogram_5bins[i] ?? 0)), [0, 0, 0, 0, 0])} />
              <p className="small muted">{t("Flat bars indicate calibration; a U shape indicates intervals that are too narrow.")}</p>
            </div>
          </div>
          <DataTable
            rows={hs.map((h) => ({ h, e: bh[h] }))}
            columns={[
              { key: "h", header: t("Horizon (days)"), render: (r) => r.h, numeric: true },
              { key: "n", header: t("n"), render: (r) => r.e.n, numeric: true },
              { key: "c50", header: t("50% coverage"), render: (r) => fmtPct(r.e.coverage_50), numeric: true },
              { key: "c90", header: t("90% coverage"), render: (r) => fmtPct(r.e.coverage_90), numeric: true },
              { key: "w", header: t("Mean WIS"), render: (r) => fmtNum(r.e.mean_wis, 1), numeric: true },
              { key: "m", header: t("MAE"), render: (r) => fmtNum(r.e.mae, 1), numeric: true },
              { key: "b", header: t("Median relative bias"), render: (r) => fmtPct(r.e.median_relative_bias), numeric: true },
              { key: "note", header: t("Calibration"), render: (r) => tx(r.e.calibration_note) },
            ]}
          />
          {d.expansion && d.expansion.n ? (
            <p className="small">
              {t("Geographic expansion ({days}-day): Brier score {brier} over {n} forecasts (base rate {rate}).", {
                days: d.expansion.horizon_days ?? "—",
                brier: fmtNum(d.expansion.brier, 3),
                n: d.expansion.n,
                rate: fmtPct(d.expansion.base_rate),
              })}
            </p>
          ) : null}
        </>
      )}
    </section>
  );
}
