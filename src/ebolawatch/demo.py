"""Synthetic demonstration dataset (fictional country 'ZZZ', clearly labelled).

Used only for demonstrations and UI development when no real data are
available. Every row is flagged ``is_synthetic`` and the interface shows a
persistent SYNTHETIC banner.
"""

from __future__ import annotations

from datetime import date, timedelta

import numpy as np
from sqlalchemy import select
from sqlalchemy.orm import Session

from .db.models import Document, Observation, Outbreak, Region, Source
from .sources.synthetic import simulate_outbreak


def load_demo(session: Session) -> dict:
    src = session.scalar(select(Source).where(Source.key == "synthetic"))
    if src is None:
        src = Source(key="synthetic", name="SYNTHETIC demonstration data (not real)", category="official_national",
                     access_method="generated", status="ok", attribution="SYNTHETIC — generated by Ebola Watch")
        session.add(src)
        session.flush()
    country = session.scalar(select(Region).where(Region.code == "ZZZ"))
    if country is None:
        country = Region(code="ZZZ", name="Synthetica (fictional)", level=0, iso3="ZZZ", centroid_lat=-30.0, centroid_lon=-30.0,
                         population=10_000_000, population_source="synthetic")
        session.add(country)
        session.flush()
    session.add(Outbreak(key=f"ZZZ-SYN-{np.random.randint(1e6)}", name="SYNTHETIC outbreak", pathogen="BDBV", primary_iso3="ZZZ",
                         declared_on=date.today() - timedelta(days=150), is_synthetic=True))
    syn = simulate_outbreak(weeks=20, seed=3, start=date.today() - timedelta(days=7 * 21))
    doc = Document(source_id=src.id, external_id=f"synthetic:{date.today()}", title="SYNTHETIC situation report", content_hash="synthetic",
                   is_synthetic=True, meta={"is_official": True})
    session.add(doc)
    session.flush()
    cum_c, cum_d = np.cumsum(syn.weekly_cases), np.cumsum(syn.weekly_deaths)
    n = 0
    for i in range(len(cum_c)):
        d = syn.start + timedelta(days=7 * (i + 1))
        for metric, v in (("cases", cum_c[i]), ("deaths", cum_d[i])):
            session.add(Observation(region_id=country.id, metric=metric, case_class="confirmed", value_type="cumulative", transmission="all",
                                    as_of=d, value=float(v), source_id=src.id, document_id=doc.id, published_at=None,
                                    citation="SYNTHETIC — not real data", extraction_method="structured",
                                    validation_status="verified", is_synthetic=True))
            n += 1
    return {"synthetic_observations": n, "region": "ZZZ"}
